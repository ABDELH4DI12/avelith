export function galleryImage(item, width = 1200) {
  const source = item.image ?? item.media;
  if (source?.startsWith("/")) return source;

  const photoId = item.id ?? source?.match(/\/photos\/(\d+)\//)?.[1];
  return photoId ? `/assets/gallery/${photoId}-${width}.webp` : source;
}

export function galleryImageSet(item) {
  const source = item.image ?? item.media;
  if (source?.startsWith("/")) return undefined;
  return `${galleryImage(item, 720)} 720w, ${galleryImage(item, 1200)} 1200w`;
}
